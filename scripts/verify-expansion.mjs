import {chromium} from 'playwright';
import fs from 'node:fs';
const base=process.env.SITE_URL||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
await page.goto(base+'/blog/lesson-budget/');
await page.locator('[name="people"]').fill('2');
await page.locator('[name="transport"]').fill('60000');
await page.locator('[name="extras"]').fill('40000');
const result=await page.locator('output').textContent();
if(!result.includes('1.400.000')||!result.includes('700.000'))errors.push('Incorrect group budget '+result);
await page.locator('[name="people"]').fill('0');
if(!(await page.locator('output').textContent()).includes('entre 1 y 20'))errors.push('Invalid participant count accepted');
await page.locator('[name="people"]').fill('2');
if(await page.locator('link[hreflang]').count()!==3)errors.push('Bilingual article has incorrect alternates');
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))errors.push('Budget page mobile overflow');
await page.locator('.editorial-tool').scrollIntoViewIfNeeded();
await page.screenshot({path:'.qa/budget-mobile.png'});
await page.goto(base+'/blog/choose-course/');
if(await page.locator('.topic-directory a').count()<5)errors.push('Missing specialized topic links');
await page.goto(base+'/en/blog/');
if(await page.locator('#article-library .blog-card').count()!==80)errors.push('Wrong English catalog');
await page.goto(base+'/blog/');
if(await page.locator('#article-library .blog-card').count()!==80)errors.push('Wrong Spanish catalog');
await browser.close();
const report={base,result,errors};fs.writeFileSync('.qa/expansion-verification.json',JSON.stringify(report,null,2));console.log(report);process.exitCode=errors.length?1:0;
